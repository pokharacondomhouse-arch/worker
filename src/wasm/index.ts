export interface ComputeWasmExports extends WebAssembly.Exports {
  add: (a: number, b: number) => number;
}

// Minimal valid WASM binary for add(i32, i32) -> i32
const WASM_BYTECODE = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
  0x01, 0x07, 0x01, 0x60, 0x02, 0x7f, 0x7f, 0x01, 0x7f,
  0x03, 0x02, 0x01, 0x00,
  0x07, 0x07, 0x01, 0x03, 0x61, 0x64, 0x64, 0x00, 0x00,
  0x0a, 0x09, 0x01, 0x07, 0x00, 0x20, 0x00, 0x20, 0x01, 0x6a, 0x0b,
]);

let wasmInstance: WebAssembly.Instance | null = null;

export async function getWorkerWasm(): Promise<ComputeWasmExports> {
  if (wasmInstance) {
    return wasmInstance.exports as ComputeWasmExports;
  }

  const { instance } = await WebAssembly.instantiate(WASM_BYTECODE);
  wasmInstance = instance;
  return instance.exports as ComputeWasmExports;
}
